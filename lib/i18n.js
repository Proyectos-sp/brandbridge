export function getText(lang) {
  const l = resolveLang(lang);
  const t = TEXT[l];
  return {
    ...t,
    lang: l,
    category: (c) => LABELS.categories[l]?.[c] || c,
    country: (c) => LABELS.countries[l]?.[c] || c,
    tag: (tag) => LABELS.tags[l][tag] || tag,
  };
}

